/**
 * 语音打断（barge-in）调参
 *
 * TTS 播放期间，麦克风帧不发往云端（防止 AI 自己的声音被转成"用户说的话"，
 * 形成自问自答的死循环）。但帧仍然在本地过一遍能量检测：浏览器的 AEC
 * （useASR 里 getUserMedia 已开 echoCancellation）会把喇叭放出来的声音消掉
 * 大部分，所以这段时间麦克风本该是安静的——出现持续的高能量，大概率是老人
 * 真的在说话。
 *
 * ⚠️ 下面这些阈值必须在**真实房间里**调。养老院有电视、有走廊动静、有别的
 * 老人说话，纯能量判据很容易误触发，而 AI 动不动把话说到一半停掉，比不能
 * 打断更糟。调参时把 useASR 里的 [BargeIn] 日志打开，对着实际环境看数。
 */

export const BARGE_IN = {
  /** 总开关。误触发严重时可以先关掉，退回"不能打断"的老行为。 */
  ENABLED: true,

  /**
   * TTS 开始后多久内不允许打断（毫秒）。
   * 防止老人自己上一句话的尾音，把刚开始的回复立刻掐掉。
   */
  GRACE_MS: 500,

  /**
   * 用开头这段时间的信号测环境底噪（毫秒），在 GRACE_MS 之内。
   * 阈值由底噪算出来，而不是写死一个绝对值——不同房间、不同音量差别很大。
   */
  BASELINE_MS: 300,

  /**
   * 判定阈值 = 底噪 × 这个倍数。调大更保守（不容易误触发，但要说得更大声）。
   */
  THRESHOLD_RATIO: 3.5,

  /**
   * 阈值下限：底噪极低（很安静的房间）时，倍数算出来的阈值会小得离谱，
   * 一点点响动就触发。用这个兜住。
   */
  MIN_THRESHOLD_RMS: 0.02,

  /**
   * 连续多少帧超过阈值才算打断（每帧约 128ms）。
   * 3 帧 ≈ 380ms，足以滤掉咳嗽、关门、电视里的单个爆音。
   */
  SUSTAINED_FRAMES: 3,

  /**
   * 预缓冲保留多少帧（每帧约 128ms）。
   * 检测本身要花 SUSTAINED_FRAMES 帧，没有预缓冲的话老人开口的头几个字会被
   * 吃掉——"我想说个事"变成"说个事"。打断成立时先把这些帧补发给云端。
   */
  PREBUFFER_FRAMES: 6,
} as const;
